import { createRequire } from "node:module";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("..", import.meta.url));
const require = createRequire(import.meta.url);
// Reuse Convex's installed, lockfile-pinned build dependency. Never install a tool.
const convexRequire = createRequire(require.resolve("convex/package.json"));
const packagePath = convexRequire.resolve("esbuild/package.json");
const installed = JSON.parse(await readFile(packagePath, "utf8"));
const lock = JSON.parse(await readFile(resolve(root, "package-lock.json"), "utf8"));
const key = relative(root, dirname(packagePath)).replaceAll("\\", "/");
if (lock.packages[key]?.version !== installed.version) throw new Error("Connect build requires the installed Convex esbuild version to match package-lock.json. Run npm ci; no installation is performed by this script.");
const esbuild = convexRequire("esbuild");
const result = await esbuild.build({ entryPoints: [resolve(root, "web/connect.ts")], bundle: true, platform: "browser", format: "iife", target: "es2022", minify: true, legalComments: "eof", write: false });
const notices = [];
for (const name of ["convex", "@convex-dev/auth"]) {
  const directory = dirname(require.resolve(`${name}/package.json`));
  const metadata = JSON.parse(await readFile(resolve(directory, "package.json"), "utf8"));
  notices.push(`${name} ${metadata.version}\n${await readFile(resolve(directory, "LICENSE"), "utf8")}`);
}
await writeFile(resolve(root, "web/THIRD_PARTY_NOTICES.txt"), notices.join("\n\n---\n\n"));
const source = `// Generated by scripts/build-connect.mjs from public browser SDK exports. Rebuild before deployment.\nexport const connectJs = ${JSON.stringify(result.outputFiles[0].text)};\nexport const connectNotices = ${JSON.stringify(notices.join("\n\n---\n\n"))};\n`;
const target = resolve(root, "convex/connectAssets.generated.ts");
if (await readFile(target, "utf8").catch(() => "") !== source) await writeFile(target, source);
